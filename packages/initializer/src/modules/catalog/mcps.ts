export const DEFAULT_VERIFIED_MCPS: McpServerId[] = [
  'ai-memory',
  'context7',
  'playwright',
  'shadcn',
];

export function getVerifiedMcpById(id: string): VerifiedMcpServer | undefined {
  return VERIFIED_MCPS.find((m) => m.id === id);
}

export function searchVerifiedMcps(query: string, category?: McpCategory): VerifiedMcpServer[] {
  const normalized = query.trim().toLowerCase();
  return VERIFIED_MCPS.filter((mcp) => {
    if (category && mcp.category !== category) return false;
    if (!normalized) return true;
    const haystack = [
      mcp.id,
      mcp.name,
      mcp.category,
      mcp.publisher,
      mcp.description,
      ...mcp.relatedTechs,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(normalized);
  });
}

/**
 * Recommends verified, audited MCP servers specifically matched to a project's stack & domains.
 */
export function recommendMcpsForProject(config: BootstrapConfig): McpServerId[] {
  const recommended = new Set<McpServerId>(['ai-memory', 'context7']);
  const fws = new Set<string>([
    ...config.stack.frameworks,
    ...config.workspace.apps.map((a) => a.framework),
    ...config.workspace.packages.map((p) => p.framework),
  ]);
  const domains = new Set<string>(config.stack.domains ?? []);

  if (config.stack.monorepo) recommended.add('nx');
  if (fws.has('nextjs')) recommended.add('nextjs-devtools');
  if (fws.has('nuxtjs')) recommended.add('nuxt');
  if (fws.has('playwright')) recommended.add('playwright');
  if (fws.has('shadcn') || fws.has('aceternity-ui')) recommended.add('shadcn');
  if (fws.has('magic-ui')) recommended.add('magic-ui');
  if (fws.has('tailwindcss') || fws.has('nativewind')) recommended.add('tailwind');
  if (fws.has('eslint')) recommended.add('eslint');
  if (fws.has('drizzle')) recommended.add('drizzle');
  if (fws.has('mongoose')) recommended.add('mongodb');
  if (fws.has('kysely') || fws.has('typeorm')) recommended.add('postgres');
  if (fws.has('tauri')) recommended.add('tauri');
  if (domains.has('financial')) {
    recommended.add('stripe');
    recommended.add('postgres');
  }

  return Array.from(recommended);
}
